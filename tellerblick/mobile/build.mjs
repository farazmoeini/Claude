// Copies ../web into www/ and writes the production config.js for the native apps.
// Usage: TB_API_BASE=https://api.example.de RC_IOS_KEY=appl_... RC_ANDROID_KEY=goog_... npm run build
import { cpSync, rmSync, readFileSync, writeFileSync, existsSync } from "node:fs";

const api = process.env.TB_API_BASE || "";
if (!/^https:\/\//.test(api)) {
  console.error("TB_API_BASE muss gesetzt sein und mit https:// beginnen (z. B. https://api.tellerblick.de).");
  process.exit(1);
}
rmSync("www", { recursive: true, force: true });
cpSync("../web", "www", { recursive: true, filter: src => !src.endsWith("reset.html") });

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const cfg = {
  apiBase: api.replace(/\/$/, ""),
  revenuecat: { ios: process.env.RC_IOS_KEY || "", android: process.env.RC_ANDROID_KEY || "" },
  entitlement: process.env.RC_ENTITLEMENT || "premium",
  supportEmail: process.env.SUPPORT_EMAIL || "support@example.com",
  privacyUrl: api + "/legal/datenschutz.html",
  termsUrl: api + "/legal/nutzungsbedingungen.html",
  imprintUrl: api + "/legal/impressum.html",
  version: pkg.version,
};
writeFileSync("www/config.js", "// generated by build.mjs\nwindow.TB_CONFIG = " + JSON.stringify(cfg, null, 2) + ";\n");
if (!cfg.revenuecat.ios || !cfg.revenuecat.android) console.warn("Hinweis: RC_IOS_KEY / RC_ANDROID_KEY fehlen – Käufe sind in diesem Build deaktiviert.");
console.log("www/ gebaut für", cfg.apiBase, existsSync("www/index.html") ? "✓" : "✗");
